CREATE TABLE COMPANY.TB_PESSOA_JURIDICA_LOG
(
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CNPJ NUMBER(14) NOT NULL,
  INSCRICAO_ESTADUAL VARCHAR2(20) NOT NULL,
  NOME_FANTASIA VARCHAR2(100) NOT NULL,
  OPERATION_TYPE VARCHAR2(10) NOT NULL, -- 'INSERT' ou 'UPDATE'
  OPERATION_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP
)
/